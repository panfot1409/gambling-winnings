"""The frozen research dossier: one manifest over every committed artifact.

``research/m2b/frozen_dossier.json`` (dossier schema version 3) supersedes
the additive provenance-v2 anchor as the single source of truth for the
dossier graph — there are never two competing graph files. It binds:

* the **discovery chain** — request plan, receipt, raw-bundle fingerprint,
  and the machine-verified discovery decision (JSON and rendered Markdown);
* the **primary acquisition chain** — request plan, receipt, raw-bundle
  fingerprint, acquisition evidence, and the selected attempt id;
* the **independent audit acquisition** — an explicit status object: either
  a full ``canonical_content_match`` record (plan/receipt/raw-bundle hashes
  plus the strict reacquisition-audit artifact) or an explicit
  ``not_performed`` reason. Never silently absent;
* the **dataset chain** — derived CSV SHA, canonical content fingerprint,
  manifest and quality-report byte anchors, and the dataset lock;
* **runtime and protocol** — the runtime contract, ``uv.lock``,
  ``pyproject.toml``, the protocol, and the protocol-registration commit;
* the **holdout and development evidence** — the committed holdout
  identity, the train/validation results and report, and the validation
  decision (JSON and Markdown).

:func:`verify_frozen_dossier` verifies graph *semantics*, not just hashes:
every artifact must hash to the manifest; every raw response must hash and
size to its receipt; receipts must agree with their plans; the raw
responses must semantically re-derive the derived OHLCV bytes; the derived
data must reproduce the canonical content fingerprint; the tracked
manifest/quality anchors must equal the regenerated bytes; the holdout
identity must recompute exactly from the verified dataset and protocol;
the train/validation results, report, and research decision must
regenerate byte-for-byte; the discovery decision must re-verify against
its raw response; the audit comparison must re-verify against the audit
raw when performed; and one package-version chain must hold throughout.
No check is silently optional in the production path.

All of this is hash-bound and tamper-evident within one repository. It is
**not** cryptographic authentication: there is no signing key and no
external attestation.
"""

